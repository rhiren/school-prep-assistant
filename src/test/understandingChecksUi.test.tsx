import { render, screen, waitFor } from "@testing-library/react";
import userEvent from "@testing-library/user-event";
import { RouterProvider, createMemoryRouter } from "react-router-dom";
import { expect, it, vi } from "vitest";
import { routes } from "../app/router";
import { AppServicesProvider, createAppServices } from "../state/AppServicesProvider";
import { TestModeProvider } from "../state/TestModeProvider";
import { MemoryStorageService } from "../storage/memoryStorageService";
import { getStudentScopedKey, STORE_NAMES } from "../storage/repositories";

it("runs a delayed check under a test profile and shows parent-only evidence without retrying the same check", async () => {
  const user = userEvent.setup();
  const store = new MemoryStorageService();
  const app = await createAppServices(store);
  const profile = await app.studentProfileService.createProfile("Check UI pilot",undefined,undefined,{profileType:"test"});
  await app.studentProfileService.setActiveStudent(profile.studentId);
  const concept = "concept-operations-with-scientific-notation";
  const practice = await app.testGenerationService.createConceptSession(concept);
  const attempt = await app.sessionService.submitSession(practice.id);
  attempt.submittedAt = new Date(Date.now()-8*86400000).toISOString();
  await store.set(STORE_NAMES.attempts,getStudentScopedKey(profile.studentId,attempt.attemptId),attempt);
  const router = createMemoryRouter(routes,{initialEntries:[`/concept/${concept}`]});
  render(<AppServicesProvider services={app}><TestModeProvider><RouterProvider router={router}/></TestModeProvider></AppServicesProvider>);
  await user.click(await screen.findByRole("button",{name:"Start understanding check"}));
  expect(await screen.findByRole("heading",{name:"Understanding Check"})).toBeInTheDocument();
  const input = screen.getByPlaceholderText("Enter a numeric answer");
  await user.type(input,"6000000");
  await user.click(screen.getByRole("button",{name:"Next"}));
  await user.click(screen.getByRole("radio",{name:/4.2 x 10\^3/}));
  await user.click(screen.getByRole("radio",{name:"I worked independently"}));
  const confirm = vi.spyOn(window,"confirm").mockReturnValue(true);
  await user.click(screen.getByRole("button",{name:"Submit test"}));
  expect(await screen.findByRole("heading",{name:"Explain your reasoning"})).toBeInTheDocument();
  expect(screen.queryByRole("button",{name:"Retry this test"})).not.toBeInTheDocument();
  const saved = (await app.progressService.getConceptAttempts(concept)).find(a=>a.understandingCheck)!;
  expect(saved.summary.correctCount).toBe(2);
  expect(saved.answerHistory?.[saved.questionIds[0]]).toHaveLength(1);
  const title = screen.getByRole("button",{name:"School Prep Assistant"});
  for(let i=0;i<5;i++) await user.click(title);
  expect(await screen.findByText("Understanding Checks: Check UI pilot")).toBeInTheDocument();
  await waitFor(()=>expect(screen.getByText("2/2 correct (2/8 observed)")).toBeInTheDocument());
  expect(screen.getByText("Reported independent")).toBeInTheDocument();
  confirm.mockRestore();
},15000);
